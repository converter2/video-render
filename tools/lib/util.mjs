/** Offset in minutes of a time zone at a given UTC instant. */
function tzOffsetMinutes(tz, date) {
  const dtf = new Intl.DateTimeFormat('en-US', {
    timeZone: tz, hourCycle: 'h23', year: 'numeric', month: '2-digit', day: '2-digit',
    hour: '2-digit', minute: '2-digit', second: '2-digit'
  });
  const p = Object.fromEntries(dtf.formatToParts(date).map(x => [x.type, x.value]));
  const asUtc = Date.UTC(+p.year, +p.month - 1, +p.day, +p.hour, +p.minute, +p.second);
  return Math.round((asUtc - date.getTime()) / 60000);
}

/** Convert a local wall-clock date (YYYY-MM-DD) and minutes-since-midnight in tz to a UTC Date. */
export function zonedToUtc(ymd, minutes, tz) {
  const [y, m, d] = ymd.split('-').map(Number);
  const guess = new Date(Date.UTC(y, m - 1, d, 0, minutes));
  const off1 = tzOffsetMinutes(tz, guess);
  let t = new Date(guess.getTime() - off1 * 60000);
  const off2 = tzOffsetMinutes(tz, t);
  if (off2 !== off1) t = new Date(guess.getTime() - off2 * 60000);
  return t;
}

/** Local calendar date YYYY-MM-DD in tz for a UTC instant. */
export function localYmd(date, tz) {
  return new Intl.DateTimeFormat('en-CA', { timeZone: tz, year: 'numeric', month: '2-digit', day: '2-digit' }).format(date);
}

export function addDays(ymd, n) {
  const [y, m, d] = ymd.split('-').map(Number);
  const t = new Date(Date.UTC(y, m - 1, d + n));
  return t.toISOString().slice(0, 10);
}

export function hhmmToMin(s) {
  const [h, m] = String(s).split(':').map(Number);
  return (h || 0) * 60 + (m || 0);
}

